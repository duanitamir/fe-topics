"""Rebuild offline full-text search after editing or highlighting topic pages."""
from pathlib import Path
from html.parser import HTMLParser
import re,json,hashlib
ROOT=Path(__file__).resolve().parents[1]
TAGS={'p','li','pre','figure','blockquote','tr','h1','h2','h3','h4'}
VOID={'meta','link','img','input','hr','br','wbr','source','area','base','embed','param','track','col'}
class Indexer(HTMLParser):
 def __init__(self,source):
  super().__init__(convert_charrefs=True);self.source=source;self.stack=[];self.capture=None;self.records=[];self.edits=[];self.headings={};self.title='';self.used=set();self.offsets=[0]
  for m in re.finditer('\n',source):self.offsets.append(m.end())
 def handle_starttag(self,tag,attrs):
  attrs=dict(attrs);inside=any(x=='section' for x in self.stack)
  if inside and self.capture is None and (tag in TAGS or (tag=='div' and attrs.get('class')=='callout')):
   pos=self.offsets[self.getpos()[0]-1]+self.getpos()[1]
   self.capture={'tag':tag,'depth':len(self.stack),'parts':[],'attrs':attrs,'pos':pos}
  if tag not in VOID:self.stack.append(tag)
 def handle_data(self,data):
  if self.capture:self.capture['parts'].append(data)
 def handle_endtag(self,tag):
  if tag in VOID:return
  assert self.stack and self.stack[-1]==tag,tag
  self.stack.pop()
  if self.capture and self.capture['depth']==len(self.stack):
   c=self.capture;self.capture=None;text=re.sub(r'\s+',' ',''.join(c['parts'])).strip()
   if not text:return
   if tag in {'h1','h2','h3','h4'}:
    level=int(tag[1]);self.headings={n:v for n,v in self.headings.items() if n<level};self.headings[level]=text
    if tag=='h1':self.title=text
   heading=' › '.join(v for n,v in sorted(self.headings.items()) if n>1)
   anchor=c['attrs'].get('id')
   if not anchor:
    base='search-'+hashlib.sha256((heading+'\0'+text).encode()).hexdigest()[:12];anchor=base;n=2
    while anchor in self.used:anchor=base+'-'+str(n);n+=1
    # IDs go on the existing block: source content and highlighting stay intact.
    self.edits.append((c['pos']+len(tag)+1,' id="'+anchor+'"'))
   self.used.add(anchor)
   self.records.append({'anchor':anchor,'heading':heading,'text':text,'kind':'Code' if tag=='pre' else 'Diagram' if tag=='figure' else 'Notes'})
records=[]
for page in sorted(ROOT.glob('*.html')):
 if page.name in {'search.html','tags.html'}:continue
 source=page.read_text()
 parser=Indexer(source);parser.used.update(re.findall(r'(?<![\w-])id="([^"]+)"', source));parser.feed(source)
 for pos,insert in sorted(parser.edits,reverse=True):source=source[:pos]+insert+source[pos:]
 page.write_text(source)
 for record in parser.records:records.append({'page':page.name,'topic':parser.title,**record})
encoded=json.dumps(records,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c').replace('\u2028','\\u2028').replace('\u2029','\\u2029')
(ROOT/'search-index.js').write_text('// Generated by tools/build_search_index.py; contains every topic passage and code example.\nwindow.NOTES_SEARCH_INDEX = '+encoded+';\n')
print(f'Indexed {len(records)} passages across {len(set(r["page"] for r in records))} topics, including {sum(r["kind"]=="Code" for r in records)} code snippets.')
