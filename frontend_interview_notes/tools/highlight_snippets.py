"""Rebuild offline syntax colors after editing snippets. Requires Pygments.
Run from any directory: pygments-enabled-python path/to/highlight_snippets.py
"""
from pathlib import Path
from html import escape
from html.parser import HTMLParser
import re
from pygments import highlight
from pygments.lexers import get_lexer_by_name
from pygments.formatters import HtmlFormatter
from pygments.lexer import RegexLexer
from pygments.token import Name, Punctuation, String, Text

ROOT = Path(__file__).resolve().parents[1]
class TextContent(HTMLParser):
    def __init__(self): super().__init__(convert_charrefs=True); self.parts=[]
    def handle_data(self, data): self.parts.append(data)
def text_content(markup):
    parser=TextContent();parser.feed(markup);return ''.join(parser.parts)
class HeaderLexer(RegexLexer):
    tokens={'root':[(r'^[A-Za-z-]+(?=:)',Name.Attribute),(r':',Punctuation),(r'[^:\n]+',String),(r'\n',Text)]}

def language_for(filename, content):
    if filename=='browser-events.html':
        return ('html','HTML + JavaScript') if content.startswith('<ul') else ('javascript','JavaScript')
    if filename=='web-security.html':
        return ('http','HTTP response header') if content.startswith('Content-Security-Policy:') else ('javascript','JavaScript · parameterized SQL')
    if filename=='frontend-performance.html' and content.startswith('HTML parsing'): return 'text','Rendering pipeline · diagram'
    if filename=='react-rendering.html':
        if any(content.startswith(x) for x in ['Rendering strategy:','Request →','Server HTML:','Time ','SERVER','Navigate to ']):return 'text','Rendering flow · diagram'
        if content.startswith('<div'):return 'html','HTML'
        return 'jsx','React · JSX'
    if filename in ['component-composition.html', 'react-hooks.html']:return 'jsx','React · JSX'
    if filename=='application-patterns.html': return 'typescript','TypeScript'
    if filename=='context-state.html':
        if content.startswith('// Message design example:'): return 'javascript','JavaScript'
        return ('typescript','TypeScript') if content.startswith('type SearchState') else ('jsx','React · JSX')
    return 'javascript','JavaScript'

formatter=HtmlFormatter(nowrap=True)
count=0
for page in sorted(ROOT.glob('*.html')):
    source=page.read_text()
    def replace(match):
        global count
        raw=text_content(match['body'])
        language,label=language_for(page.name,raw)
        if page.stem in {'javascript-mechanics','async-programming','typescript','http-networking','build-tooling','accessibility','backend-api','graphql'}:
            declared=re.search(r'class="language-([^"]+)"', match['code_attrs'])
            assert declared, (page.name, 'Declare each example language')
            language=declared[1]
            label={'javascript':'JavaScript','typescript':'TypeScript','jsx':'React · JSX','graphql':'GraphQL','sql':'SQL','json':'JSON','http':'HTTP response headers','html':'HTML'}[language]
        lexer=HeaderLexer(ensurenl=False,stripnl=False) if language=='http' else get_lexer_by_name(language,ensurenl=False,stripnl=False)
        colored=escape(raw) if language=='text' else highlight(raw,lexer,formatter)
        if text_content(colored)==raw+'\n': colored=colored[:-1]
        assert text_content(colored)==raw,(page.name,'Snippet content changed')
        count+=1
        pre_id = re.search(r'\bid="([^"]+)"', match['pre_attrs'])
        preserved_id = (' id="' + escape(pre_id[1], quote=True) + '"') if pre_id else ''
        return '<pre' + preserved_id + ' class="code-example" data-language="'+escape(label,quote=True)+'"><code class="language-'+language+'">'+colored+'</code></pre>'
    source=re.sub(r'<pre\b(?P<pre_attrs>[^>]*)>\s*<code\b(?P<code_attrs>[^>]*)>(?P<body>.*?)</code>\s*</pre>',replace,source,flags=re.S)
    page.write_text(source)
css=formatter.get_style_defs('.code-example')
# Use a readable dark theme; generated selectors are kept for all token types.
from pygments.styles import get_style_by_name
css=HtmlFormatter(style='github-dark').get_style_defs('.code-example')
(ROOT/'syntax.css').write_text('/* Generated by tools/highlight_snippets.py. Offline syntax highlighting. */\n'+css+'\n')
print(f'Highlighted and labeled {count} snippets; verified decoded snippet text is unchanged.')
