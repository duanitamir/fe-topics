"""Build offline reference excerpts from canonical indexed passages; never duplicate authored prose."""
from pathlib import Path
from urllib.parse import urlsplit, unquote
import json,re
ROOT=Path(__file__).resolve().parents[1]
s=(ROOT/'search-index.js').read_text();records=json.loads(s.split('window.NOTES_SEARCH_INDEX = ',1)[1].rstrip(';\n'))
by_page={}
for item in records:by_page.setdefault(item['page'],[]).append(item)
previews={}
for page,items in by_page.items():
 source=(ROOT/page).read_text()
 headings={anchor:int(level) for level,anchor in re.findall(r'<h([1-4])\b[^>]*\bid="([^"]+)"',source)}
 by_anchor={item['anchor']:i for i,item in enumerate(items)}
 aliases={}
 for section,h in re.findall(r'<(?:section|article|div)\b[^>]*\bid="([^"]+)"[^>]*aria-labelledby="([^"]+)"',source):aliases[section]=h
 for anchor in set(by_anchor)|set(aliases):
  actual=aliases.get(anchor,anchor)
  if actual not in by_anchor:continue
  i=by_anchor[actual];item=items[i]
  if actual in headings:
   title=item['text'];blocks=[]
   for nxt in items[i+1:]:
    if nxt['anchor'] in headings:
     if headings[nxt['anchor']] <= headings[actual]:break
     continue
    if nxt['kind']=='Notes':blocks.append(nxt['text'])
    if len(blocks)==3:break
  else:title=item['heading'].split(' › ')[-1] or item['topic'];blocks=[item['text']]
  if not blocks:continue
  previews[page+'#'+anchor]={'topic':item['topic'],'title':title,'blocks':blocks}
encoded=json.dumps(previews,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')
(ROOT/'reference-previews.js').write_text('// Generated by tools/build_reference_previews.py\nwindow.NOTES_REFERENCE_PREVIEWS = '+encoded+';\n')
print(f'Built {len(previews)} offline reference previews.')
